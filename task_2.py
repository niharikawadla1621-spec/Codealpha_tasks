import pretty_midi
import numpy as np

# Read uploaded MIDI file
midi_data = pretty_midi.PrettyMIDI(
    "al_adagi (1).mid"
)

# Extract instruments
instruments = [
    inst for inst in midi_data.instruments
    if not inst.is_drum
]

if not instruments:
    raise ValueError("No musical instruments found!")

# Select instrument with most notes
best_instrument = max(
    instruments,
    key=lambda inst: len(inst.notes)
)

# Extract notes
notes = []

for note in sorted(
    best_instrument.notes,
    key=lambda n: n.start
):
    notes.append(note.pitch)

notes = np.array(notes)

print("Music data extracted successfully!")
print("Total notes:", len(notes))
print("First 20 notes:", notes[:20])

# Prepare training data

sequence_length = 30

X = []
y = []

for i in range(len(notes) - sequence_length):

    X.append(notes[i:i + sequence_length])

    y.append(notes[i + sequence_length])

# Convert into NumPy arrays

X = np.array(X, dtype=np.int32)
y = np.array(y, dtype=np.int32)

print("Training data prepared successfully!")
print("Input shape:", X.shape)
print("Output shape:", y.shape)
print("Total training samples:", len(X))

import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, Embedding, LSTM, Dense

# Build AI music generation model

model = Sequential([
    Input(shape=(30,), dtype="int32"),

    Embedding(input_dim=128, output_dim=64),

    LSTM(128),

    Dense(128, activation="softmax")
])

# Compile the model

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

# Display model details

model.summary()

history = model.fit(
    X,
    y,
    epochs=30,
    batch_size=32
)

print("AI Model Training Completed!")

import numpy as np

# Start with the first 30 notes
generated = list(X[0])

# Generate 200 new notes
for i in range(200):

    input_notes = np.array(
        generated[-30:]
    ).reshape(1, 30)

    # Predict next note
    prediction = model.predict(
        input_notes,
        verbose=0
    )[0]

    # Select a note based on prediction
    next_note = np.random.choice(
        128,
        p=prediction
    )

    generated.append(int(next_note))

# Keep only newly generated notes
generated_notes = generated[30:]

print("AI music generated successfully!")
print("Total generated notes:", len(generated_notes))
print("Generated notes:", generated_notes[:20])

import pretty_midi

# Create a new MIDI file
new_midi = pretty_midi.PrettyMIDI()

# Create piano instrument
piano = pretty_midi.Instrument(
    program=0
)

start_time = 0

# Add generated notes
for pitch in generated_notes:

    note = pretty_midi.Note(
        velocity=100,
        pitch=int(pitch),
        start=start_time,
        end=start_time + 0.3
    )

    piano.notes.append(note)

    start_time += 0.3

# Add piano to MIDI
new_midi.instruments.append(piano)

# Save generated music
new_midi.write("AI_Generated_Music.mid")

print("Music saved successfully!")

